"""The containerlab topology file. Addresses and routes are applied with `exec` after each container starts."""

from __future__ import annotations

from pathlib import Path

import yaml

from .topology import (
    DEFAULT_VIA,
    EXTRA_ADDRESSES,
    FEED_PORT,
    FRR_IMAGE,
    LAB,
    LAB_IMAGE,
    LINKS,
    MGMT_NET,
    NODES,
    PERSPECTIVES,
    RTR_PORT,
    interfaces,
)


def _exec(node: str) -> list[str]:
    cmds = ["ip route del default"]  # the management default route: nothing may point off the box
    cmds += [f"ip addr add {ip} dev {dev}" for dev, ip, _ in interfaces()[node]]
    cmds += [f"ip addr add {ip} dev {dev}" for ip, dev in EXTRA_ADDRESSES.get(node, [])]
    if node in DEFAULT_VIA:
        cmds.append(f"ip route add default via {DEFAULT_VIA[node]}")
    if node == "ca":
        for p in PERSPECTIVES:
            if p.table != "main":
                cmds.append(f"ip rule add from {p.ip} table {p.table}")
                cmds.append(f"ip route add default via {p.gateway} dev {p.dev} table {p.table}")
    return cmds


def _node(node: str) -> dict:
    n = NODES[node]
    d: dict = {"kind": "linux", "mgmt-ipv4": n.mgmt}
    if n.role == "router":
        d["image"] = FRR_IMAGE
        d["binds"] = [f"{node}:/etc/frr"]
        d["exec"] = _exec(node)
        if node == "collector":
            d["binds"] += ["../feed.py:/lab/feed.py:ro", "feed.json:/lab/feed.json:ro"]
            d["exec"].append(
                f"sh -c 'nohup python3 /lab/feed.py --port {FEED_PORT} --config /lab/feed.json >/tmp/feed.log 2>&1 &'"
            )
    elif n.role == "rpki":
        d["image"] = LAB_IMAGE
        d["binds"] = ["rpki:/rpki:ro"]
        d["cmd"] = f"stayrtr -cache /rpki/rpki.json -checktime=false -refresh 10 -bind :{RTR_PORT}"
        d["exec"] = ["ip route del default"]
    else:
        d["image"] = LAB_IMAGE
        d["binds"] = [f"{node}:/lab"]
        d["cmd"] = {"resolver": "entry-resolver.sh", "ca": "sleep infinity"}.get(n.role, "entry-host.sh")
        d["exec"] = _exec(node)
    return d


def render_clab(build: Path) -> None:
    topo = {
        "name": LAB,
        "mgmt": {
            "network": f"{LAB}-mgmt",
            "ipv4-subnet": MGMT_NET,
            "driver-opts": {"com.docker.network.bridge.enable_ip_masquerade": "false"},
        },
        "topology": {
            "nodes": {name: _node(name) for name in NODES},
            "links": [],
        },
    }
    ifs = interfaces()
    for link in LINKS:
        a_dev = next(dev for dev, ip, _ in ifs[link.a] if ip == link.a_ip)
        b_dev = next(dev for dev, ip, _ in ifs[link.b] if ip == link.b_ip)
        topo["topology"]["links"].append({"endpoints": [f"{link.a}:{a_dev}", f"{link.b}:{b_dev}"]})
    (build / "lab.clab.yml").write_text("# generated by lab/render/clab.py\n" + yaml.safe_dump(topo, sort_keys=False))
